#!/usr/bin/env python3
"""Validate the pruned PyTorch graph produced by `^py-networkx~default`.

The graph is generated by Bazel's vendored Spack inside the insula. This guard
keeps the checked-in artifact honest: networkx's default extras must stay off,
the expensive extras chain must stay absent, and every Spack-hash change from
the previous lean-font graph must have an explicit ticket reason.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


DEFAULT_MUST_DROP = (
    "llvm",
    "py-llvmlite",
    "py-numba",
    "py-pandas",
    "py-scipy",
    "py-matplotlib",
)

DEFAULT_NETWORKX_DEPS = (
    "py-pip",
    "py-setuptools",
    "py-wheel",
    "python",
    "python-venv",
)


def _load_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def _nodes_by_package(graph: dict) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for node in graph.get("nodes", []):
        package = node.get("package")
        if isinstance(package, str):
            out.setdefault(package, []).append(node)
    return out


def _package_signatures(graph: dict) -> dict[str, set[tuple[str, str]]]:
    signatures: dict[str, set[tuple[str, str]]] = {}
    for node in graph.get("nodes", []):
        package = node.get("package")
        version = node.get("version")
        spack_hash = node.get("spack_hash")
        if isinstance(package, str) and isinstance(version, str) and isinstance(spack_hash, str):
            signatures.setdefault(package, set()).add((version, spack_hash))
    return signatures


def _parse_expected_hash_changes(items: list[str]) -> dict[str, str]:
    parsed: dict[str, str] = {}
    for item in items:
        package, sep, reason = item.partition("=")
        if not sep or not package or not reason:
            raise ValueError(f"expected hash change must be '<package>=<reason>', got {item!r}")
        parsed[package] = reason
    return parsed


def check_graphs(
    old: dict,
    new: dict,
    *,
    must_drop: set[str] | None = None,
    networkx_deps: set[str] | None = None,
    expected_hash_changes: dict[str, str] | None = None,
    expected_n_nodes: int | None = None,
    expected_dropped_count: int | None = None,
    forbid_added_packages: bool = True,
) -> tuple[list[str], dict[str, object]]:
    must_drop = must_drop or set(DEFAULT_MUST_DROP)
    networkx_deps = networkx_deps or set(DEFAULT_NETWORKX_DEPS)
    expected_hash_changes = expected_hash_changes or {}
    errors: list[str] = []

    old_by_package = _nodes_by_package(old)
    new_by_package = _nodes_by_package(new)
    old_packages = set(old_by_package)
    new_packages = set(new_by_package)
    dropped = sorted(old_packages - new_packages)
    added = sorted(new_packages - old_packages)

    actual_node_count = len(new.get("nodes", []))
    declared_node_count = new.get("n_nodes")
    if declared_node_count != actual_node_count:
        errors.append(f"new graph n_nodes={declared_node_count!r} but contains {actual_node_count} nodes")
    if expected_n_nodes is not None and actual_node_count != expected_n_nodes:
        errors.append(f"new graph has {actual_node_count} nodes; expected {expected_n_nodes}")
    if expected_dropped_count is not None and len(dropped) != expected_dropped_count:
        errors.append(f"new graph dropped {len(dropped)} packages; expected {expected_dropped_count}")
    if forbid_added_packages and added:
        errors.append(f"new graph adds unexpected packages: {', '.join(added)}")

    present_forbidden = sorted(pkg for pkg in must_drop if pkg in new_packages)
    if present_forbidden:
        errors.append(f"pruned graph still contains forbidden package(s): {', '.join(present_forbidden)}")

    networkx_nodes = new_by_package.get("py-networkx", [])
    if len(networkx_nodes) != 1:
        errors.append(f"pruned graph must contain exactly one py-networkx node, found {len(networkx_nodes)}")
    else:
        networkx = networkx_nodes[0]
        params = networkx.get("parameters", {})
        if params.get("default") is not False:
            errors.append(f"py-networkx default variant is {params.get('default')!r}; expected False")
        if params.get("extra") is not False:
            errors.append(f"py-networkx extra variant is {params.get('extra')!r}; expected False")
        actual_deps = {dep.get("name") for dep in networkx.get("deps", []) if isinstance(dep.get("name"), str)}
        if actual_deps != networkx_deps:
            errors.append(
                "py-networkx deps are "
                f"{', '.join(sorted(actual_deps))}; expected {', '.join(sorted(networkx_deps))}"
            )

    old_sigs = _package_signatures(old)
    new_sigs = _package_signatures(new)
    hash_changes = sorted(pkg for pkg in old_packages & new_packages if old_sigs.get(pkg) != new_sigs.get(pkg))
    expected = set(expected_hash_changes)
    unexpected = sorted(set(hash_changes) - expected)
    stale = sorted(expected - set(hash_changes))
    if unexpected:
        errors.append(f"unexplained hash change(s): {', '.join(unexpected)}")
    if stale:
        errors.append(f"stale expected hash-change reason(s): {', '.join(stale)}")

    report = {
        "old_n_nodes": len(old.get("nodes", [])),
        "new_n_nodes": actual_node_count,
        "dropped": dropped,
        "added": added,
        "hash_changes": {pkg: expected_hash_changes.get(pkg, "") for pkg in hash_changes},
    }
    return errors, report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--old-graph", type=Path, required=True)
    parser.add_argument("--new-graph", type=Path, required=True)
    parser.add_argument("--expected-n-nodes", type=int)
    parser.add_argument("--expected-dropped-count", type=int)
    parser.add_argument("--must-drop", action="append", default=list(DEFAULT_MUST_DROP))
    parser.add_argument("--networkx-dep", action="append", default=list(DEFAULT_NETWORKX_DEPS))
    parser.add_argument("--expected-hash-change", action="append", default=[])
    parser.add_argument("--allow-added-packages", action="store_true")
    args = parser.parse_args(argv)

    try:
        expected_hash_changes = _parse_expected_hash_changes(args.expected_hash_change)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 2

    errors, report = check_graphs(
        _load_json(args.old_graph),
        _load_json(args.new_graph),
        must_drop=set(args.must_drop),
        networkx_deps=set(args.networkx_dep),
        expected_hash_changes=expected_hash_changes,
        expected_n_nodes=args.expected_n_nodes,
        expected_dropped_count=args.expected_dropped_count,
        forbid_added_packages=not args.allow_added_packages,
    )
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1

    print(
        "py-torch networkx prune check passed: "
        f"{report['old_n_nodes']} -> {report['new_n_nodes']} nodes, "
        f"{len(report['dropped'])} dropped packages, "
        f"{len(report['hash_changes'])} documented hash changes"
    )
    for package, reason in sorted(report["hash_changes"].items()):  # type: ignore[union-attr]
        print(f"hash-change {package}: {reason}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
