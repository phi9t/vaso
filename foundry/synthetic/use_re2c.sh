#!/usr/bin/env bash
set -euo pipefail

find_native_prefix() {
  local base hit
  for base in "${RUNFILES_DIR:-}" "$PWD" "$PWD/.." "$0.runfiles"; do
    [[ -n "$base" && -d "$base" ]] || continue
    hit="$(find "$base" -type d -path "*re2c_native*/prefix" 2>/dev/null | head -1)"
    if [[ -n "$hit" ]]; then echo "$hit"; return 0; fi
  done
  return 1
}

PREFIX="$(find_native_prefix)"
input="$(mktemp)"
output="$(mktemp)"
trap 'rm -f "$input" "$output"' EXIT

cat > "$input" <<'EOF'
/*!re2c
    re2c:define:YYCTYPE = char;
    re2c:yyfill:enable = 0;
    * { return 0; }
*/
EOF

"$PREFIX/bin/re2c" --version | grep -q 're2c 4.4'
"$PREFIX/bin/re2c" --no-generation-date -o "$output" "$input"
if ! grep -q 'Generated by re2c 4.4' "$output" || ! grep -q 'return 0' "$output"; then
  echo "unexpected re2c generated output:" >&2
  sed -n '1,80p' "$output" >&2
  exit 1
fi
test -r "$PREFIX/lib/libre2c.so.0.0.0"
test -r "$PREFIX/share/re2c/stdlib/c"
echo "re2c:4.4:ok"
