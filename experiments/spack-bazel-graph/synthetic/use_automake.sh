#!/usr/bin/env bash
set -euo pipefail

find_native_prefix() {
  local marker="$1"
  local base hit
  for base in "${RUNFILES_DIR:-}" "$PWD" "$PWD/.." "$0.runfiles"; do
    [[ -n "$base" && -d "$base" ]] || continue
    hit="$(find "$base" -type d -path "*${marker}*/prefix" 2>/dev/null | head -1)"
    if [[ -n "$hit" ]]; then echo "$hit"; return 0; fi
  done
  return 1
}

PREFIX="$(find_native_prefix automake_native)"
AUTOCONF_PREFIX="$(find_native_prefix autoconf_native)"
PERL_PREFIX="$(find_native_prefix perl_native)"
export PATH="$PREFIX/bin:$AUTOCONF_PREFIX/bin:$PERL_PREFIX/bin:${PATH:-}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cat > "$work/configure.ac" <<'EOF'
AC_INIT([vaso-automake-smoke], [1.0])
AM_INIT_AUTOMAKE([foreign])
AC_CONFIG_FILES([Makefile])
AC_OUTPUT
EOF

cat > "$work/Makefile.am" <<'EOF'
EXTRA_DIST = README
EOF

touch "$work/README"

(
  cd "$work"
  aclocal
  automake --add-missing --foreign
)
test -f "$work/Makefile.in"
grep -q 'Makefile.in generated by automake' "$work/Makefile.in"
automake --version | grep -q 'automake (GNU automake) 1.18.1'
echo "automake:1.18.1:ok"
